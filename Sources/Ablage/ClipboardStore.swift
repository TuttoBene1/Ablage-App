import AppKit
import CryptoKit
import ImageIO
import UniformTypeIdentifiers

struct ClipItem: Identifiable, Codable, Equatable {
    enum Kind: String, Codable { case text, image, files }

    var id = UUID()
    var kind: Kind
    var text: String?
    var imageFile: String?
    var imageHash: String?
    var pixelWidth: Int?
    var pixelHeight: Int?
    var filePaths: [String]?
    var sourceBundleID: String?
    var sourceName: String?
    var date = Date()
    var pinned = false

    var fileURLs: [URL] { (filePaths ?? []).map { URL(fileURLWithPath: $0) } }

    /// Single-line friendly preview.
    var title: String {
        switch kind {
        case .text:
            let collapsed = (text ?? "")
                .split(whereSeparator: { $0.isWhitespace || $0.isNewline })
                .joined(separator: " ")
            return String(collapsed.prefix(400))
        case .image:
            return sourceName == PasteboardOrigin.screenshotName ? "Bildschirmfoto" : "Bild"
        case .files:
            let urls = fileURLs
            if urls.count == 1 { return urls[0].lastPathComponent }
            return "\(urls.count) Objekte"
        }
    }

    func matches(_ query: String) -> Bool {
        let q = query.trimmingCharacters(in: .whitespaces)
        guard !q.isEmpty else { return true }
        switch kind {
        case .text: return (text ?? "").localizedStandardContains(q)
        case .image: return title.localizedStandardContains(q) || "bild".localizedStandardContains(q) || (sourceName ?? "").localizedStandardContains(q)
        case .files: return (filePaths ?? []).contains { $0.localizedStandardContains(q) }
        }
    }
}

/// Marks pasteboard contents written by Ablage itself (screenshots, recordings).
enum PasteboardOrigin {
    static let type = NSPasteboard.PasteboardType("local.ablage.origin")
    static let screenshotName = "Bildschirmfoto"
    static let recordingName = "Bildschirmaufnahme"
}

@MainActor
final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [ClipItem] = []

    /// Unpinned entries kept in the history. Pinned entries are never pushed out.
    let maxRecent = 25

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount = -1
    private var timer: Timer?
    private var saveWork: DispatchWorkItem?
    private let thumbnails = NSCache<NSString, NSImage>()
    private var icons: [String: NSImage] = [:]

    private let directory: URL
    var imagesDirectory: URL { directory.appendingPathComponent("Images", isDirectory: true) }
    private var historyURL: URL { directory.appendingPathComponent("history.json") }

    /// Pasteboard types that signal passwords or other content that must not be recorded.
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
    ]

    init(directory custom: URL? = nil) {
        let support = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        directory = custom ?? support.appendingPathComponent("Ablage", isDirectory: true)
        try? FileManager.default.createDirectory(at: imagesDirectory, withIntermediateDirectories: true)
    }

    var pinnedCount: Int { items.filter(\.pinned).count }

    // MARK: Monitoring

    func start() {
        load()
        let timer = Timer(timeInterval: 0.35, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
        poll()
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count

        guard let types = pasteboard.types, !types.isEmpty else { return }
        if types.contains(where: { Self.ignoredTypes.contains($0.rawValue) }) { return }

        var sourceName: String?
        var sourceBundleID: String?
        if let origin = pasteboard.string(forType: PasteboardOrigin.type) {
            sourceName = origin
        } else if let app = NSWorkspace.shared.frontmostApplication {
            sourceName = app.localizedName
            sourceBundleID = app.bundleIdentifier
        }

        // Follow the owner's preferred order of representations.
        for type in types {
            switch type {
            case .fileURL:
                if let urls = pasteboard.readObjects(forClasses: [NSURL.self],
                                                     options: [.urlReadingFileURLsOnly: true]) as? [URL],
                   !urls.isEmpty {
                    addFiles(urls, sourceName: sourceName, bundleID: sourceBundleID)
                    return
                }
            case .string:
                if let string = pasteboard.string(forType: .string), !string.isBlank {
                    addText(string, sourceName: sourceName, bundleID: sourceBundleID)
                    return
                }
            case .png, .tiff:
                if let data = pasteboard.data(forType: type) {
                    addImage(data, isPNG: type == .png, sourceName: sourceName, bundleID: sourceBundleID)
                    return
                }
            default:
                continue
            }
        }
        if let string = pasteboard.string(forType: .string), !string.isBlank {
            addText(string, sourceName: sourceName, bundleID: sourceBundleID)
        }
    }

    private func addText(_ text: String, sourceName: String?, bundleID: String?) {
        let value = text.count > 200_000 ? String(text.prefix(200_000)) : text
        if bumpExisting(where: { $0.kind == .text && $0.text == value }, sourceName: sourceName, bundleID: bundleID) { return }
        insert(ClipItem(kind: .text, text: value, sourceBundleID: bundleID, sourceName: sourceName))
    }

    private func addFiles(_ urls: [URL], sourceName: String?, bundleID: String?) {
        let paths = urls.map(\.path)
        if bumpExisting(where: { $0.kind == .files && $0.filePaths == paths }, sourceName: sourceName, bundleID: bundleID) { return }
        insert(ClipItem(kind: .files, filePaths: paths, sourceBundleID: bundleID, sourceName: sourceName))
    }

    private func addImage(_ data: Data, isPNG: Bool, sourceName: String?, bundleID: String?) {
        let hash = SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
        if bumpExisting(where: { $0.imageHash == hash }, sourceName: sourceName, bundleID: bundleID) { return }

        let id = UUID()
        let date = Date()
        let fileName = id.uuidString + ".png"
        let url = imagesDirectory.appendingPathComponent(fileName)

        Task { @MainActor [weak self] in
            // Decode / re-encode off the main thread; large TIFFs can take a moment.
            let dimensions: (Int, Int)? = await Task.detached(priority: .userInitiated) {
                guard let rep = NSBitmapImageRep(data: data) else { return nil }
                let png = isPNG ? data : rep.representation(using: .png, properties: [:])
                guard let png, (try? png.write(to: url, options: .atomic)) != nil else { return nil }
                return (rep.pixelsWide, rep.pixelsHigh)
            }.value
            guard let self, let dimensions else { return }
            var item = ClipItem(kind: .image, sourceBundleID: bundleID, sourceName: sourceName)
            item.id = id
            item.date = date
            item.imageFile = fileName
            item.imageHash = hash
            item.pixelWidth = dimensions.0
            item.pixelHeight = dimensions.1
            self.insert(item)
        }
    }

    /// Adds a prepared entry directly (used by the `--snapshot` design preview).
    func addPrepared(_ item: ClipItem) {
        items.append(item)
        items.sort { $0.date > $1.date }
    }

    /// Moves an existing identical entry to the top instead of creating a duplicate.
    private func bumpExisting(where predicate: (ClipItem) -> Bool, sourceName: String?, bundleID: String?) -> Bool {
        guard let index = items.firstIndex(where: predicate) else { return false }
        var item = items.remove(at: index)
        item.date = Date()
        if let sourceName { item.sourceName = sourceName; item.sourceBundleID = bundleID }
        items.insert(item, at: 0)
        scheduleSave()
        return true
    }

    private func insert(_ item: ClipItem) {
        items.insert(item, at: 0)
        items.sort { $0.date > $1.date }
        trim()
        scheduleSave()
    }

    private func trim() {
        var recent = 0
        var removed: [ClipItem] = []
        items = items.filter { item in
            if item.pinned { return true }
            recent += 1
            if recent > maxRecent { removed.append(item); return false }
            return true
        }
        removed.forEach(deleteFiles)
    }

    // MARK: Actions

    func copyToPasteboard(_ item: ClipItem) {
        pasteboard.clearContents()
        switch item.kind {
        case .text:
            pasteboard.setString(item.text ?? "", forType: .string)
        case .image:
            if let url = imageURL(for: item), let data = try? Data(contentsOf: url) {
                PasteboardWriter.writeImage(png: data, to: pasteboard)
            }
        case .files:
            pasteboard.writeObjects(item.fileURLs as [NSURL])
        }
        // Our own write: don't re-import, just move the entry to the top.
        lastChangeCount = pasteboard.changeCount
        if let index = items.firstIndex(where: { $0.id == item.id }) {
            var moved = items.remove(at: index)
            moved.date = Date()
            items.insert(moved, at: 0)
            scheduleSave()
        }
    }

    func togglePin(_ id: UUID) {
        guard let index = items.firstIndex(where: { $0.id == id }) else { return }
        items[index].pinned.toggle()
        if !items[index].pinned {
            items.sort { $0.date > $1.date }
            trim()
        }
        scheduleSave()
    }

    func delete(_ id: UUID) {
        guard let index = items.firstIndex(where: { $0.id == id }) else { return }
        deleteFiles(items.remove(at: index))
        scheduleSave()
    }

    func clearHistory() {
        let removed = items.filter { !$0.pinned }
        items.removeAll { !$0.pinned }
        removed.forEach(deleteFiles)
        scheduleSave()
    }

    // MARK: Images & icons

    func imageURL(for item: ClipItem) -> URL? {
        guard let file = item.imageFile else { return nil }
        return imagesDirectory.appendingPathComponent(file)
    }

    func thumbnail(for item: ClipItem) -> NSImage? {
        let key = item.id.uuidString as NSString
        if let cached = thumbnails.object(forKey: key) { return cached }
        guard let url = imageURL(for: item),
              let source = CGImageSourceCreateWithURL(url as CFURL, nil) else { return nil }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceThumbnailMaxPixelSize: 120,
            kCGImageSourceCreateThumbnailWithTransform: true,
        ]
        guard let cg = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }
        let image = NSImage(cgImage: cg, size: NSSize(width: CGFloat(cg.width) / 2, height: CGFloat(cg.height) / 2))
        thumbnails.setObject(image, forKey: key)
        return image
    }

    func fileIcon(for item: ClipItem) -> NSImage {
        let urls = item.fileURLs
        guard let first = urls.first else { return NSWorkspace.shared.icon(for: .data) }
        if urls.count > 1 { return NSWorkspace.shared.icon(for: .folder) }
        if FileManager.default.fileExists(atPath: first.path) {
            return NSWorkspace.shared.icon(forFile: first.path)
        }
        return NSWorkspace.shared.icon(for: UTType(filenameExtension: first.pathExtension) ?? .data)
    }

    func appIcon(for bundleID: String?) -> NSImage? {
        guard let bundleID else { return nil }
        if let cached = icons[bundleID] { return cached }
        guard let url = NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundleID) else { return nil }
        let icon = NSWorkspace.shared.icon(forFile: url.path)
        icons[bundleID] = icon
        return icon
    }

    // MARK: Persistence

    private func deleteFiles(_ item: ClipItem) {
        guard let url = imageURL(for: item) else { return }
        thumbnails.removeObject(forKey: item.id.uuidString as NSString)
        try? FileManager.default.removeItem(at: url)
    }

    private func load() {
        guard let data = try? Data(contentsOf: historyURL),
              let decoded = try? JSONDecoder().decode([ClipItem].self, from: data) else { return }
        let fm = FileManager.default
        items = decoded.filter { item in
            guard item.kind == .image else { return true }
            guard let url = imageURL(for: item) else { return false }
            return fm.fileExists(atPath: url.path)
        }
        // Remove image files that are no longer referenced.
        let referenced = Set(items.compactMap(\.imageFile))
        if let files = try? fm.contentsOfDirectory(atPath: imagesDirectory.path) {
            for file in files where !referenced.contains(file) {
                try? fm.removeItem(at: imagesDirectory.appendingPathComponent(file))
            }
        }
    }

    private func scheduleSave() {
        saveWork?.cancel()
        let work = DispatchWorkItem { [weak self] in
            MainActor.assumeIsolated { self?.saveNow() }
        }
        saveWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.6, execute: work)
    }

    func saveNow() {
        saveWork?.cancel()
        guard let data = try? JSONEncoder().encode(items) else { return }
        try? data.write(to: historyURL, options: .atomic)
    }
}

enum PasteboardWriter {
    static func writeImage(png: Data, to pasteboard: NSPasteboard = .general, origin: String? = nil) {
        let item = NSPasteboardItem()
        item.setData(png, forType: .png)
        if let tiff = NSBitmapImageRep(data: png)?.tiffRepresentation(using: .lzw, factor: 0) {
            item.setData(tiff, forType: .tiff)
        }
        if let origin { item.setString(origin, forType: PasteboardOrigin.type) }
        pasteboard.clearContents()
        pasteboard.writeObjects([item])
    }

    static func writeFile(_ url: URL, origin: String? = nil) {
        let item = NSPasteboardItem()
        item.setString(url.absoluteString, forType: .fileURL)
        item.setString(url.lastPathComponent, forType: .string)
        if let origin { item.setString(origin, forType: PasteboardOrigin.type) }
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.writeObjects([item])
    }
}

private extension String {
    var isBlank: Bool { trimmingCharacters(in: .whitespacesAndNewlines).isEmpty }
}
